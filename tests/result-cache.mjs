import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import ts from 'typescript'
const source = await fs.readFile('src/result-cache.ts', 'utf8')
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText
const { AgentResultCache, MODEL_RESULT_CHARACTERS, MAX_CACHED_RESULT_CHARACTERS, MAX_CACHED_RESULTS } = await import('data:text/javascript;base64,' + Buffer.from(compiled).toString('base64'))
const cache = new AgentResultCache()
const a = {}, b = {}
const full = 'visible first page '.repeat(900)
const id = cache.put(a, full)
assert.ok(id)
assert.equal(cache.read(b, id), undefined)
const first = cache.read(a, id)
assert.equal(first.text.length, MODEL_RESULT_CHARACTERS)
const second = cache.read(a, id, first.nextOffset)
assert.equal(first.text + second.text, full)
assert.equal(second.nextOffset, null)
assert.throws(() => cache.read(a, id, -1), /range/)
assert.throws(() => cache.read(a, id, 0, MODEL_RESULT_CHARACTERS + 1), /range/)
assert.throws(() => cache.read(a, id, full.length + 1), /exceeds/)
for (let i = 0; i < MAX_CACHED_RESULTS; i++) cache.put(a, 'small')
assert.equal(cache.read(a, id), undefined)
const bigOne = cache.put(a, 'x'.repeat(600_000))
const bigTwo = cache.put(a, 'y'.repeat(600_000))
assert.equal(cache.read(a, bigOne), undefined)
assert.equal(cache.read(a, bigTwo, 0, 5).text, 'yyyyy')
assert.equal(cache.put(a, 'z'.repeat(MAX_CACHED_RESULT_CHARACTERS + 1)), undefined)
const bId = cache.put(b, 'other owner')
cache.clear(a)
assert.equal(cache.read(a, bigTwo), undefined)
assert.equal(cache.read(b, bId).text, 'other owner')
cache.clear()
assert.equal(cache.read(b, bId), undefined)
console.log('result cache: PASS (exact paging, ownership, char/item bounds, eviction, clearing)')
